"""Internal benchmark set: scaffold, annotation templates, validation and leakage check.

Files (under `paths.benchmark`, all UTF-8 with BOM so Excel / Google Sheets open Arabic correctly):

* ``benchmark_items.csv``  – one row per input text. ``status`` is candidate | selected | rejected.
  The final benchmark is the set of ``selected`` rows.
* ``references.csv``       – one row per item: human reference summary, key points, writer,
  reviewer and review status. Never generated by a model (proposal requirement).
* ``external_sources_template.csv`` – metadata sheet for organizational-report texts
  imported from a folder of .txt files with :func:`import_text_folder`.

Reference summaries follow docs/reference_guideline.md.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Mapping, Sequence

import numpy as np
import pandas as pd

from ..io_utils import sha256_text, utc_now
from ..text.normalize import arabic_letter_ratio, normalize_for_matching, normalize_for_model
from ..text.words import count_words
from .dedup import NearDupIndex, minhash

ITEM_COLUMNS = [
    "sample_id", "domain", "status", "source", "source_id", "source_url", "license",
    "retrieved_date", "word_count", "length_bin", "content_hash", "text", "source_highlight", "notes",
]
REFERENCE_COLUMNS = [
    "sample_id", "domain", "input_words", "ref_min_words", "ref_max_words", "ref_target_words",
    "reference_summary", "key_points", "reference_words", "reference_source",
    "writer_id", "reviewer_id", "review_status", "review_notes", "guideline_version",
]
SOURCE_COLUMNS = ["file_name", "source", "source_url", "license", "retrieved_date", "notes"]
STATUSES = {"candidate", "selected", "rejected"}
REVIEW_STATUSES = {"pending", "approved", "needs_revision", "rejected"}
DOMAIN_PREFIX = {"news": "NEWS", "org_report": "ORG"}

ITEMS_FILE = "benchmark_items.csv"
REFS_FILE = "references.csv"
SOURCES_TEMPLATE_FILE = "external_sources_template.csv"


# ------------------------------------------------------------------ helpers

def content_hash(text: str) -> str:
    return sha256_text(normalize_for_matching(text))


def reference_bounds(input_words: int, bcfg: Mapping) -> tuple[int, int, int]:
    """(hard_min, hard_max, target) reference length in words for an input of `input_words`."""
    lo = max(bcfg["reference_min_words"], math.ceil(bcfg["reference_hard_min_ratio"] * input_words))
    hi = min(bcfg["reference_max_words"], math.floor(bcfg["reference_hard_max_ratio"] * input_words))
    target = min(hi, max(lo, round(bcfg["reference_target_ratio"] * input_words)))
    return lo, hi, target


def parse_key_points(s: str) -> list[str]:
    parts = str(s).replace("|", "\n").split("\n")
    return [p.strip(" -•*\t") for p in parts if p.strip(" -•*\t")]


def length_bin(n: int, edges: Sequence[int]) -> str:
    for a, b in zip(edges[:-1], edges[1:]):
        if a <= n < b:
            return f"{a}-{b - 1}"
    return "out_of_range"


def read_csv(p: Path) -> pd.DataFrame:
    return pd.read_csv(p, dtype=str, keep_default_na=False, encoding="utf-8-sig")


def write_csv(df: pd.DataFrame, p: Path) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    df.to_csv(tmp, index=False, encoding="utf-8-sig")
    tmp.replace(p)


# ------------------------------------------------------------------ scaffold

def select_news_candidates(test: pd.DataFrame, bcfg: Mapping, seed: int) -> pd.DataFrame:
    """Stratified sample of XL-Sum test articles inside the benchmark length range.

    `test` must have columns id,url,title,summary,text,text_words,has_duplicates (articles
    involved in any exact/near-duplicate pair are excluded to keep the benchmark clean).
    """
    lo, hi = bcfg["input_min_words"], bcfg["input_max_words"]
    edges = bcfg["length_bins"]
    pool = test[(test.text_words >= lo) & (test.text_words <= hi) & ~test.has_duplicates].copy()
    pool["length_bin"] = pool.text_words.map(lambda n: length_bin(n, edges))
    bins = sorted(pool.length_bin.unique(), key=lambda b: int(b.split("-")[0]))
    n_total = bcfg["news_candidates"]
    per_bin = {b: n_total // len(bins) + (1 if i < n_total % len(bins) else 0) for i, b in enumerate(bins)}
    rng = np.random.default_rng(seed)
    picks = []
    for b in bins:
        grp = pool[pool.length_bin == b]
        take = min(per_bin[b], len(grp))
        picks.append(grp.iloc[rng.choice(len(grp), size=take, replace=False)])
    sel = pd.concat(picks).sort_values(["length_bin", "id"]).reset_index(drop=True)

    items = pd.DataFrame({
        "sample_id": [f"NEWS-{i + 1:04d}" for i in range(len(sel))],
        "domain": "news",
        "status": "candidate",
        "source": "XL-Sum Arabic test split (BBC Arabic)",
        "source_id": sel.id.values,
        "source_url": sel.url.values,
        "license": "CC BY-NC-SA 4.0",
        "retrieved_date": utc_now()[:10],
        "word_count": sel.text_words.astype(str).values,
        "length_bin": sel.length_bin.values,
        "content_hash": [content_hash(t) for t in sel.text],
        "text": sel.text.values,
        "source_highlight": sel.summary.values,  # 1-sentence XL-Sum summary, NOT the reference
        "notes": "",
    })
    return items[ITEM_COLUMNS]


def reference_template(items: pd.DataFrame, bcfg: Mapping) -> pd.DataFrame:
    rows = []
    for _, r in items.iterrows():
        n = int(r.word_count) if str(r.word_count).isdigit() else count_words(r.text)
        lo, hi, tgt = reference_bounds(n, bcfg)
        rows.append({
            "sample_id": r.sample_id, "domain": r.domain, "input_words": n,
            "ref_min_words": lo, "ref_max_words": hi, "ref_target_words": tgt,
            "reference_summary": "", "key_points": "", "reference_words": "",
            "reference_source": "human", "writer_id": "", "reviewer_id": "",
            "review_status": "pending", "review_notes": "",
            "guideline_version": bcfg["guideline_version"],
        })
    return pd.DataFrame(rows, columns=REFERENCE_COLUMNS)


def write_scaffold(bench_dir: Path, items: pd.DataFrame, bcfg: Mapping) -> dict:
    """Create the CSVs. Existing files are NEVER overwritten (they hold annotator work)."""
    written, kept = [], []
    targets = {
        ITEMS_FILE: lambda: items,
        REFS_FILE: lambda: reference_template(items, bcfg),
        SOURCES_TEMPLATE_FILE: lambda: pd.DataFrame(columns=SOURCE_COLUMNS),
    }
    for name, make in targets.items():
        p = bench_dir / name
        if p.exists():
            kept.append(name)
        else:
            write_csv(make(), p)
            written.append(name)
    return {"written": written, "kept_existing": kept}


def import_text_folder(
    bench_dir: Path, folder: Path, domain: str, bcfg: Mapping, sources_csv: Path | None = None
) -> pd.DataFrame:
    """Append .txt files from `folder` as candidate items (+ empty reference rows).

    Metadata per file comes from `sources_csv` (columns: SOURCE_COLUMNS, keyed by file_name).
    Files whose content hash is already present are skipped, so the call is idempotent.
    """
    if domain not in DOMAIN_PREFIX:
        raise ValueError(f"unknown domain {domain!r}")
    items = read_csv(bench_dir / ITEMS_FILE)
    refs = read_csv(bench_dir / REFS_FILE)
    meta = read_csv(sources_csv).set_index("file_name") if sources_csv else pd.DataFrame()
    prefix = DOMAIN_PREFIX[domain]
    existing = set(items.content_hash)
    nums = [int(s.split("-")[1]) for s in items.sample_id if s.startswith(prefix + "-")]
    next_n = max(nums, default=0) + 1

    new_rows = []
    for f in sorted(Path(folder).glob("*.txt")):
        text = normalize_for_model(f.read_text(encoding="utf-8-sig"))
        h = content_hash(text)
        if h in existing:
            continue
        m = meta.loc[f.name] if f.name in meta.index else {}
        n = count_words(text)
        new_rows.append({
            "sample_id": f"{prefix}-{next_n:04d}", "domain": domain, "status": "candidate",
            "source": m.get("source", ""), "source_id": f.name, "source_url": m.get("source_url", ""),
            "license": m.get("license", ""), "retrieved_date": m.get("retrieved_date", ""),
            "word_count": str(n), "length_bin": length_bin(n, bcfg["length_bins"]),
            "content_hash": h, "text": text, "source_highlight": "", "notes": m.get("notes", ""),
        })
        existing.add(h)
        next_n += 1
    if new_rows:
        add = pd.DataFrame(new_rows, columns=ITEM_COLUMNS)
        write_csv(pd.concat([items, add], ignore_index=True), bench_dir / ITEMS_FILE)
        new_refs = reference_template(add, bcfg).astype(str)
        write_csv(pd.concat([refs, new_refs], ignore_index=True), bench_dir / REFS_FILE)
    return pd.DataFrame(new_rows, columns=ITEM_COLUMNS)


# ------------------------------------------------------------------ validation

@dataclass
class ValidationReport:
    strict: bool
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    stats: dict = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.errors

    def to_dict(self) -> dict:
        return {"ok": self.ok, "strict": self.strict, "checked_utc": utc_now(),
                "stats": self.stats, "errors": self.errors, "warnings": self.warnings}

    def summary(self, max_lines: int = 15) -> str:
        head = f"{'PASS' if self.ok else 'FAIL'} (strict={self.strict}): {len(self.errors)} errors, {len(self.warnings)} warnings"
        lines = [head, f"stats: {self.stats}"]
        lines += [f"  ERROR   {e}" for e in self.errors[:max_lines]]
        if len(self.errors) > max_lines:
            lines.append(f"  ... {len(self.errors) - max_lines} more errors")
        lines += [f"  WARNING {w}" for w in self.warnings[:max_lines]]
        if len(self.warnings) > max_lines:
            lines.append(f"  ... {len(self.warnings) - max_lines} more warnings")
        return "\n".join(lines)


def validate(items: pd.DataFrame, refs: pd.DataFrame, bcfg: Mapping, strict: bool,
             near_dup_k: int = 5, near_dup_threshold: float = 0.8, num_perm: int = 128) -> ValidationReport:
    """Check the benchmark files.

    strict=False (while annotating): pending work is a warning.
    strict=True  (freeze): only `selected` rows count, all must have approved references,
                 domain balance must be met.
    """
    rep = ValidationReport(strict=strict)
    E, W = rep.errors.append, rep.warnings.append

    for name, df, cols in (("items", items, ITEM_COLUMNS), ("references", refs, REFERENCE_COLUMNS)):
        missing = [c for c in cols if c not in df.columns]
        if missing:
            E(f"{name}: missing columns {missing}")
    if rep.errors:
        return rep

    bad_status = items[~items.status.isin(STATUSES)]
    for sid in bad_status.sample_id:
        E(f"{sid}: status must be one of {sorted(STATUSES)}")
    dup_ids = items.sample_id[items.sample_id.duplicated()].tolist()
    if dup_ids:
        E(f"duplicate sample_id values: {dup_ids}")

    active_status = {"selected"} if strict else {"selected", "candidate"}
    active = items[items.status.isin(active_status)]

    lo, hi = bcfg["input_min_words"], bcfg["input_max_words"]
    hashes: dict[str, str] = {}
    sigs = []
    for _, r in active.iterrows():
        sid = r.sample_id
        if r.domain not in bcfg["domains"]:
            E(f"{sid}: domain {r.domain!r} not in {bcfg['domains']}")
        if not r.text.strip():
            E(f"{sid}: empty text")
            continue
        n = count_words(r.text)
        if str(r.word_count) != str(n):
            W(f"{sid}: stored word_count {r.word_count} != recomputed {n}")
        if not lo <= n <= hi:
            E(f"{sid}: {n} words, outside {lo}-{hi}")
        if arabic_letter_ratio(r.text) < bcfg["min_arabic_ratio"]:
            E(f"{sid}: Arabic-script ratio below {bcfg['min_arabic_ratio']}")
        h = content_hash(r.text)
        if r.content_hash and r.content_hash != h:
            E(f"{sid}: content_hash mismatch (text edited after registration?)")
        if h in hashes:
            E(f"{sid}: exact duplicate of {hashes[h]}")
        hashes.setdefault(h, sid)
        if not r.source.strip():
            (E if strict else W)(f"{sid}: missing source")
        if not r.license.strip():
            (E if strict else W)(f"{sid}: missing license / usage terms")
        sigs.append((sid, minhash(normalize_for_matching(r.text), near_dup_k, num_perm)))

    # near-duplicates inside the benchmark (O(n^2) is fine for a few hundred items)
    for i in range(len(sigs)):
        for j in range(i + 1, len(sigs)):
            s = sigs[i][1].jaccard(sigs[j][1])
            if s >= near_dup_threshold:
                E(f"{sigs[j][0]}: near-duplicate of {sigs[i][0]} (jaccard~{s:.2f})")

    counts = active.domain.value_counts().to_dict()
    for d in bcfg["domains"]:
        c = counts.get(d, 0)
        if c < bcfg["min_per_domain"]:
            (E if strict else W)(f"domain {d}: {c} items < required {bcfg['min_per_domain']}")

    # ---- references
    ref_ids = set(refs.sample_id)
    for sid in sorted(ref_ids - set(items.sample_id)):
        E(f"references.csv: {sid} not in benchmark_items.csv")
    refs_by_id = refs.drop_duplicates("sample_id", keep="last").set_index("sample_id")
    if refs.sample_id.duplicated().any():
        E(f"references.csv: duplicate sample_id rows {refs.sample_id[refs.sample_id.duplicated()].tolist()}")

    n_approved = 0
    for _, r in active.iterrows():
        sid = r.sample_id
        pend = E if strict else W
        if sid not in refs_by_id.index:
            pend(f"{sid}: no reference row")
            continue
        ref = refs_by_id.loc[sid]
        summ = ref.reference_summary.strip()
        if not summ:
            pend(f"{sid}: reference summary missing")
            continue
        n_in = count_words(r.text)
        n_ref = count_words(summ)
        rlo, rhi, _ = reference_bounds(n_in, bcfg)
        if not rlo <= n_ref <= rhi:
            E(f"{sid}: reference has {n_ref} words, allowed {rlo}-{rhi} for {n_in}-word input")
        ratio = n_ref / n_in
        t, tol = bcfg["reference_target_ratio"], bcfg["reference_ratio_tolerance"]
        if not t - tol <= ratio <= t + tol:
            W(f"{sid}: reference ratio {ratio:.2f} outside guideline {t - tol:.2f}-{t + tol:.2f}")
        if arabic_letter_ratio(summ) < bcfg["min_arabic_ratio"]:
            E(f"{sid}: reference is not predominantly Arabic script")
        if len(parse_key_points(ref.key_points)) < bcfg["min_key_points"]:
            pend(f"{sid}: fewer than {bcfg['min_key_points']} key points")
        if ref.reference_source not in ("human", "source"):
            E(f"{sid}: reference_source must be 'human' or 'source'")
        if ref.review_status not in REVIEW_STATUSES:
            E(f"{sid}: review_status must be one of {sorted(REVIEW_STATUSES)}")
        if not ref.writer_id.strip() or not ref.reviewer_id.strip():
            pend(f"{sid}: writer_id and reviewer_id are required")
        elif ref.writer_id.strip() == ref.reviewer_id.strip():
            E(f"{sid}: reviewer must differ from writer")
        if ref.review_status != "approved":
            pend(f"{sid}: review_status is {ref.review_status!r}, not approved")
        else:
            n_approved += 1
        if ref.guideline_version != bcfg["guideline_version"]:
            W(f"{sid}: guideline_version {ref.guideline_version!r} != current {bcfg['guideline_version']!r}")

    rep.stats = {
        "items_total": int(len(items)),
        "active": int(len(active)),
        "active_by_domain": {k: int(v) for k, v in counts.items()},
        "selected": int((items.status == "selected").sum()),
        "rejected": int((items.status == "rejected").sum()),
        "references_approved": n_approved,
    }
    return rep


# ------------------------------------------------------------------ leakage

def leakage_check(items: pd.DataFrame, train_index: NearDupIndex, train_hashes: Mapping[str, str],
                  train_urls: Mapping[str, str]) -> dict:
    """Benchmark texts must not appear (exactly, by URL, or near-duplicated) in training data.

    `train_hashes` / `train_urls` map content hash / URL -> document key for every document
    that may be used for training or model selection (XL-Sum train + validation).
    """
    leaks = []
    active = items[items.status != "rejected"]
    for _, r in active.iterrows():
        norm = normalize_for_matching(r.text)
        h = sha256_text(norm)
        if h in train_hashes:
            leaks.append({"sample_id": r.sample_id, "type": "exact", "match": train_hashes[h], "similarity": 1.0})
            continue
        if r.source_url and r.source_url in train_urls:
            leaks.append({"sample_id": r.sample_id, "type": "url", "match": train_urls[r.source_url], "similarity": None})
            continue
        hits = train_index.query(norm)
        if hits:
            leaks.append({"sample_id": r.sample_id, "type": "near", "match": hits[0][0], "similarity": round(hits[0][1], 4)})
    return {"checked_utc": utc_now(), "items_checked": int(len(active)), "n_leaks": len(leaks),
            "ok": not leaks, "leaks": leaks}
